def format_medical_data(raw_data):
    """
    数据格式化：将结构化字典转为自然语言文本
    :param raw_data: 结构化医疗数据（列表）
    :return: 格式化后的文本列表
    """
    formatted_texts = []
    for item in raw_data:
        parts = []
        for key, value in item.items():
            parts.append(f"{key}：{value}")
        # 按“药物/场景”分类标题
        if "药物名称" in item:
            formatted_text = f"【药物】{item['药物名称']}\n" + "；".join(parts)
        elif "场景" in item:
            formatted_text = f"【场景】{item['场景']}\n" + "；".join(parts)
        else:
            formatted_text = "；".join(parts)
        formatted_texts.append(formatted_text)
    return formatted_texts

# 1. 格式化结构化数据
medical_texts = format_medical_data(medical_raw_data)

# 2. 分块（文档教学的“切割文档”步骤，适配长文本）
medical_chunks = []
for text in medical_texts:
    chunks = split_document(text, chunk_size=150, chunk_overlap=10)
    medical_chunks.extend(chunks)
